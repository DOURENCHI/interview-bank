    removed = 0
    for f in CONTENT.glob("Q-*.md"):
        if re.search(r"^algo_seed: true", f.read_text(encoding="utf-8"), re.M):
            f.unlink()
            removed += 1
    if removed:
        print(f"清理旧算法索引 {removed} 张")

