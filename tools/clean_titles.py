# 兜底规则：这些模式即使没在 DROP 里，也说明标题是教学叙事而非面试题。
BAD_PATTERNS = [
    r"^这份", r"^本(讲|手)|阅读结构|固定结构$", r"^图 ?[0-9]",
    r"^[AB]\.[0-9]", r"逐条核对|原文照录|贴在显示器上|投入产出图",
    r"^和你的", r"^第 ?[①-⑩0-9] ?步", r"^用 ?namespace ?解决",
]


def set_title(path: Path, title: str) -> bool:
    s = path.read_text(encoding="utf-8")
    new, n = re.subn(r"^title: .*$", f"title: {title}", s, count=1, flags=re.M)
    if n == 0 or new == s:
        return False
    path.write_text(new, encoding="utf-8")
    return True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry", action="store_true")
    args = ap.parse_args()

    files = {p.stem.split("-")[0] + "-" + p.stem.split("-")[1]: p
             for p in CONTENT.rglob("Q-*.md")}

    dropped = retitled = kept = skipped = 0
    for qid, path in sorted(files.items()):
        s = path.read_text(encoding="utf-8")
        m = re.search(r"^title: (.+)$", s, re.M)

        if qid in DROP:
            dropped += 1
            if not args.dry:
                path.unlink()
            continue

        if qid in RETITLE:
            retitled += 1
            if not args.dry:
                set_title(path, RETITLE[qid])
            continue

        if m and any(re.search(p, m.group(1)) for p in BAD_PATTERNS):
            skipped += 1
            if not args.dry:
                path.unlink()
            continue

        kept += 1

    print(f"改写 {retitled} 条 ｜ 删除 {dropped + skipped} 条"
          f"（显式 {dropped} + 规则 {skipped}）｜ 保留 {kept} 条")
    if args.dry:
        print("（--dry 模式，未改动任何文件）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
