def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry", action="store_true")
    args = ap.parse_args()

    removed = 0
    for f in CONTENT.glob("Q-*.md"):
        txt = f.read_text(encoding="utf-8")
        if re.search(r"^proj_seed: true", txt, re.M) and f"sub: {SUB}" in txt:
            f.unlink()
            removed += 1
    if removed:
        print(f"清理旧跟骨题卡 {removed} 张")

    nums = [int(m.group(1)) for f in CONTENT.glob("Q-*.md")
            if (m := re.match(r"Q-(\d+)", f.name))]
    nxt = max(nums + [ID_BASE]) + 1
    start = nxt

    FMT = """---
id: {qid}
title: {title}
module: 01_project
sub: """ + SUB + """
priority: P1
difficulty: {diff}
roles: [AI算法, 感知]
companies: [联影医疗, 迈瑞医疗, 西门子医疗]
qtype: project
status: indexed
source_type: self_exp
source_ref: """ + REF + """
verified_at: 2026-11-09
tags: [项目深挖, 医学影像, U-Net, 图文, 待填答案]
auto: true
proj_seed: true
---

{body}"""

    for it in ITEMS:
        if nxt >= ID_BASE + SPAN:
            print(f"⚠ 号段用尽，停在 {nxt}")
            return 1
        qid = f"Q-{nxt:04d}"
        if not args.dry:
            (CONTENT / f"{qid}-proj.md").write_text(
                FMT.format(qid=qid, title=it["title"], diff=it["diff"], body=it["body"]),
                encoding="utf-8")
        nxt += 1

    print(f"{'预览' if args.dry else '生成'} {len(ITEMS)} 道 → Q-{start:04d} ~ Q-{nxt-1:04d}  sub={SUB}（答案待填）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
