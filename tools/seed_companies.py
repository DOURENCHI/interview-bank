    OUT.mkdir(parents=True, exist_ok=True)
    for c in COMPANIES:
        pos = "\n".join(f"| {n} | {f} | {d} |" for n, f, d in c["positions"])
        p0 = "\n".join(f"- {x}" for x in c["p0"])
        p1 = "\n".join(f"- {x}" for x in c["p1"])
        drill = "\n".join(f"| {o} | `{m}` | {d} |" for o, m, d in c["drill"])
        (OUT / f"{c['slug']}.md").write_text(
            TPL.format(name=c["name"], title=c["title"], priority=c["priority"],
                       city=c["city"], positions=pos, p0=p0, p1=p1,
                       drill=drill, notes=c["notes"]),
            encoding="utf-8")
    print(f"生成 {len(COMPANIES)} 份公司档案 → companies/")
    return 0


